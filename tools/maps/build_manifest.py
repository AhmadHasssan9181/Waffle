#!/usr/bin/env python3
"""Regenerate MANIFEST.json and SHA256SUMS.txt for a map pack directory.

The pack is rebuilt often (tiles, place index, fonts), and a stale manifest makes
`install_offline_pack.py --verify` fail for the wrong reason. Run this after any pack rebuild:

    python tools/maps/build_manifest.py
    python tools/maps/build_manifest.py --pack build/release-preview28

It writes:

    MANIFEST.json    [{"file": ..., "bytes": ..., "sha256": ...}, ...]
    SHA256SUMS.txt   <sha256>  <file>   (sha256sum format)

Release artefacts (APKs/AAB) are included when present, because the manifest doubles as the
checksum list for a preview drop.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

# Stable ordering so the manifest diff is readable.
PREFERRED_ORDER = [
    "app-arm64-v8a-release.apk",
    "app-armeabi-v7a-release.apk",
    "app-release.aab",
    "pakistan_vector.pmtiles",
    "pakistan_places.pmtiles",
    "places_search.db",
    "fonts.zip",
    "sprite.zip",
]

# Generated by this script, never hashed.
EXCLUDED = {"MANIFEST.json", "SHA256SUMS.txt", "NOTES.md"}


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as fp:
        for chunk in iter(lambda: fp.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def ordered(files: list[Path]) -> list[Path]:
    rank = {name: i for i, name in enumerate(PREFERRED_ORDER)}
    return sorted(files, key=lambda p: (rank.get(p.name, len(rank)), p.name))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--pack",
        type=Path,
        default=ROOT / "build" / "release-preview28",
        help="pack directory (default: build/release-preview28)",
    )
    parser.add_argument(
        "--quiet", action="store_true", help="only print the summary line"
    )
    args = parser.parse_args()

    pack: Path = args.pack.resolve()
    if not pack.is_dir():
        sys.exit(f"pack directory not found: {pack}")

    files = ordered(
        [
            entry
            for entry in pack.iterdir()
            if entry.is_file() and entry.name not in EXCLUDED
        ]
    )
    if not files:
        sys.exit(f"nothing to hash in {pack}")

    entries = []
    sums = []
    for path in files:
        digest = sha256(path)
        size = path.stat().st_size
        entries.append({"file": path.name, "bytes": size, "sha256": digest})
        sums.append(f"{digest}  {path.name}")
        if not args.quiet:
            print(f"  {path.name:32s} {size:>14,} bytes  {digest[:16]}…")

    manifest = pack / "MANIFEST.json"
    manifest.write_text(
        json.dumps(entries, indent=4, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    checksums = pack / "SHA256SUMS.txt"
    checksums.write_text("\n".join(sums) + "\n", encoding="utf-8")

    total = sum(entry["bytes"] for entry in entries)
    print(
        f"\nWrote {manifest.name} ({len(entries)} files, {total / 1024 ** 2:.0f} MB) "
        f"and {checksums.name} in {pack}"
    )


if __name__ == "__main__":
    main()
